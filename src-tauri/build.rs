//! Generates the dependency list shown on the About page from the actual
//! `Cargo.lock` / `package.json` / installed `node_modules`, so the page cannot
//! drift from what is really linked.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    // The custom manifest declares `longPathAware` on top of the stock Common-Controls
    // dependency, so `\\?\`-free paths beyond MAX_PATH resolve instead of failing.
    tauri_build::try_build(
        tauri_build::Attributes::new().windows_attributes(
            tauri_build::WindowsAttributes::new()
                .app_manifest(include_str!("windows-app-manifest.xml")),
        ),
    )
    .expect("tauri build script failed");

    println!("cargo:rerun-if-changed=Cargo.lock");
    println!("cargo:rerun-if-changed=Cargo.toml");
    println!("cargo:rerun-if-changed=../package.json");
    println!("cargo:rerun-if-changed=../package-lock.json");

    let mut rows: Rows = BTreeMap::new();
    collect_rust(&mut rows);
    collect_npm(&mut rows);
    let rows: Vec<_> = rows.into_values().collect();

    let mut generated = String::from("// @generated by build.rs from Cargo.lock / package.json\n");
    generated.push_str("pub const DEPS: &[(&str, &str, &str, &str, &str)] = &[\n");
    for (kind, name, version, license, repository) in rows {
        generated.push_str(&format!(
            "    (\"{kind}\", \"{}\", \"{}\", \"{}\", \"{}\"),\n",
            escape(&name),
            escape(&version),
            escape(&license),
            escape(&repository)
        ));
    }
    generated.push_str("];\n");

    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("deps.rs");
    fs::write(out, generated).unwrap();
}

fn escape(value: &str) -> String {
    value.replace('\\', "\\\\").replace('"', "\\\"")
}

fn direct_rust_deps() -> Vec<String> {
    let manifest = fs::read_to_string("Cargo.toml").unwrap_or_default();
    let mut in_deps = false;
    let mut names = Vec::new();
    for line in manifest.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with('[') {
            in_deps = trimmed == "[dependencies]" || trimmed == "[build-dependencies]";
            continue;
        }
        if !in_deps || trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        if let Some((name, _)) = trimmed.split_once('=') {
            names.push(name.trim().to_string());
        }
    }
    names
}

type Row = (String, String, String, String, String);
type Rows = BTreeMap<(String, String), Row>;

fn collect_rust(rows: &mut Rows) {
    let Ok(lock) = fs::read_to_string("Cargo.lock") else {
        return;
    };
    // name -> highest version in the lock file
    let mut versions: BTreeMap<String, String> = BTreeMap::new();
    let mut current: Option<String> = None;
    for line in lock.lines() {
        let trimmed = line.trim();
        if trimmed == "[[package]]" {
            current = None;
        } else if let Some(rest) = trimmed.strip_prefix("name = ") {
            current = Some(rest.trim_matches('"').to_string());
        } else if let Some(rest) = trimmed.strip_prefix("version = ") {
            if let Some(name) = &current {
                let version = rest.trim_matches('"').to_string();
                versions
                    .entry(name.clone())
                    .and_modify(|existing| {
                        if version > *existing {
                            *existing = version.clone();
                        }
                    })
                    .or_insert(version);
            }
        }
    }

    for name in direct_rust_deps() {
        let version = versions.get(&name).cloned().unwrap_or_else(|| "?".into());
        let (license, repository) = rust_metadata(&name, &version);
        let license = license.unwrap_or_else(|| "see crate".into());
        // crates.io is the fallback so every row is still a useful link when the crate
        // does not declare a repository.
        let repository = repository.unwrap_or_else(|| format!("https://crates.io/crates/{name}"));
        rows.insert(
            ("rust".into(), name.clone()),
            ("rust".into(), name, version, license, repository),
        );
    }
}

fn registry_sources() -> Vec<PathBuf> {
    let home = std::env::var_os("CARGO_HOME")
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("USERPROFILE").map(|p| PathBuf::from(p).join(".cargo")));
    let Some(home) = home else { return Vec::new() };
    let registry = home.join("registry").join("src");
    let Ok(entries) = fs::read_dir(registry) else {
        return Vec::new();
    };
    entries.filter_map(|e| e.ok()).map(|e| e.path()).collect()
}

/// License and repository from the `[package]` table of a downloaded crate. Both live in
/// the registry copy, which is the same manifest cargo resolved.
fn rust_metadata(name: &str, version: &str) -> (Option<String>, Option<String>) {
    for source in registry_sources() {
        let manifest = source.join(format!("{name}-{version}")).join("Cargo.toml");
        let Ok(text) = fs::read_to_string(&manifest) else {
            continue;
        };
        let license = package_field(&text, "license").or_else(|| {
            let name = package_field(&text, "license-file")?;
            license_file_label(&manifest.with_file_name(name))
        });
        let repository = package_field(&text, "repository")
            .or_else(|| package_field(&text, "homepage"))
            .and_then(|value| normalize_repo_url(&value));
        return (license, repository);
    }
    (None, None)
}

/// Reads a quoted string from `[package]` only: dependency tables can contain similarly
/// named keys, and the first match in the file is not necessarily package metadata.
fn package_field(text: &str, key: &str) -> Option<String> {
    let prefix = format!("{key} = ");
    let mut in_package = false;
    for line in text.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with('[') {
            in_package = trimmed == "[package]";
            continue;
        }
        if !in_package {
            continue;
        }
        if let Some(rest) = trimmed.strip_prefix(&prefix) {
            return Some(rest.trim().trim_matches('"').to_string());
        }
    }
    None
}

/// Crates that ship a `license-file` instead of an SPDX `license` field still need a
/// readable answer. Identify the common texts; a custom file that adds terms is marked so
/// the page does not claim the plain license alone applies.
fn license_file_label(path: &Path) -> Option<String> {
    let text = fs::read_to_string(path).ok()?;
    let lower = text.to_ascii_lowercase();
    let base = if lower.contains("apache license") && lower.contains("version 2.0") {
        "Apache-2.0"
    } else if lower.contains("mit license") {
        "MIT"
    } else if lower.contains("gnu lesser general public license") {
        "LGPL"
    } else if lower.contains("gnu general public license") {
        "GPL"
    } else if lower.contains("redistribution and use in source and binary forms") {
        "BSD"
    } else {
        return Some("see LICENSE file".into());
    };
    let extra = lower.contains("further condition") || lower.contains("additional term");
    Some(if extra {
        format!("{base} (additional terms)")
    } else {
        base.to_string()
    })
}

/// Turns the many repository spellings found in package metadata into one browsable
/// HTTPS URL (`git+https://…`, `git://…`, `git@github.com:owner/repo.git`, …).
fn normalize_repo_url(raw: &str) -> Option<String> {
    let mut url = raw.trim().split('#').next()?.trim().to_string();
    if let Some(rest) = url.strip_prefix("git+") {
        url = rest.to_string();
    }
    if let Some(rest) = url.strip_prefix("git://") {
        url = format!("https://{rest}");
    }
    if let Some(rest) = url.strip_prefix("ssh://git@") {
        url = format!("https://{rest}");
    }
    if let Some(rest) = url.strip_prefix("git@") {
        if let Some((host, path)) = rest.split_once(':') {
            url = format!("https://{host}/{}", path.trim_start_matches('/'));
        }
    }
    if let Some(rest) = url.strip_prefix("http://") {
        url = format!("https://{rest}");
    }
    if !url.starts_with("https://") {
        return None;
    }
    url = url.split('?').next()?.trim_end_matches('/').to_string();
    if let Some(stripped) = url.strip_suffix(".git") {
        url = stripped.to_string();
    }
    (!url.is_empty()).then_some(url)
}

fn collect_npm(rows: &mut Rows) {
    let root = Path::new("..");
    let Ok(pkg) = fs::read_to_string(root.join("package.json")) else {
        return;
    };
    let Ok(json) = serde_json::from_str::<serde_json::Value>(&pkg) else {
        return;
    };
    let mut names: Vec<(String, bool)> = Vec::new();
    for section in ["dependencies", "devDependencies"] {
        if let Some(map) = json.get(section).and_then(|v| v.as_object()) {
            for (name, range) in map {
                names.push((
                    name.clone(),
                    range
                        .as_str()
                        .map(|r| r.starts_with('^') || r.starts_with('~'))
                        .unwrap_or(false),
                ));
            }
        }
    }
    names.sort_by(|a, b| a.0.cmp(&b.0));
    names.dedup_by(|a, b| a.0 == b.0);

    for (name, _) in names {
        let installed = root.join("node_modules").join(&name).join("package.json");
        let meta = fs::read_to_string(&installed)
            .ok()
            .and_then(|text| serde_json::from_str::<serde_json::Value>(&text).ok());
        let version = meta
            .as_ref()
            .and_then(|m| m.get("version"))
            .and_then(|v| v.as_str())
            .unwrap_or("not installed")
            .to_string();
        let license = meta
            .as_ref()
            .map(npm_license)
            .unwrap_or_else(|| "see package".to_string());
        // npmjs is the fallback for packages that omit a repository field.
        let repository = meta
            .as_ref()
            .and_then(npm_repository)
            .unwrap_or_else(|| format!("https://www.npmjs.com/package/{name}"));
        rows.insert(
            ("npm".into(), name.clone()),
            ("npm".into(), name, version, license, repository),
        );
    }
}

/// Newer packages use a string, some older ones an object (`{ "type": "MIT" }`), and a
/// few use a legacy `licenses` array.
fn npm_license(meta: &serde_json::Value) -> String {
    match meta.get("license") {
        Some(serde_json::Value::String(value)) => value.clone(),
        Some(serde_json::Value::Object(object)) => object
            .get("type")
            .and_then(|value| value.as_str())
            .unwrap_or("see package")
            .to_string(),
        _ => {
            let ids: Vec<&str> = meta
                .get("licenses")
                .and_then(|value| value.as_array())
                .map(|entries| {
                    entries
                        .iter()
                        .filter_map(|entry| {
                            entry
                                .get("type")
                                .and_then(|value| value.as_str())
                                .or_else(|| entry.as_str())
                        })
                        .collect()
                })
                .unwrap_or_default();
            if ids.is_empty() {
                "see package".to_string()
            } else {
                ids.join(" OR ")
            }
        }
    }
}

fn npm_repository(meta: &serde_json::Value) -> Option<String> {
    let raw = match meta.get("repository") {
        Some(serde_json::Value::String(value)) => Some(value.as_str()),
        Some(serde_json::Value::Object(object)) => {
            object.get("url").and_then(|value| value.as_str())
        }
        _ => None,
    }?;
    normalize_repo_url(raw)
}
