/** Localized sentence for a backend error code; unknown codes stay readable. */
export function errorMessage(lang: Lang, code: string): string {
  const table: Record<string, string> = lang === 'en' ? enErrors : zhErrors
  return table[code] ?? (lang === 'en' ? `Unknown error (${code})` : `未知错误（${code}）`)
}